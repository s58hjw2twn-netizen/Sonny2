"""Command-line verification of an externally generated Sonny ONE coding receipt.

Read-only: no code generation, commits, deployment, or paid model calls.
Usage:
 python -m sonny_one.development_controller.verify_receipt_cli \\
   --receipt receipt.json --task-id DEV-001 --parent-sha FULL_40_HEX_SHA

The caller must supply a receipt generated by a separately authorized coding
executor. Exit status 0 means GitHub evidence matched at verification time,
not that the code is safe, correct, or ready to deploy.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from sonny_one.development_controller.github_readonly_transport import github_readonly_json
from sonny_one.development_controller.github_verifier import verify_github_receipt

_SHA = re.compile(r"^[0-9a-f]{40}$")
_MAX_RECEIPT_BYTES = 8192


def check_receipt_file(path: Path, *, task_id: str, parent_sha: str,
                       fetch_json=github_readonly_json) -> dict:
    if not isinstance(task_id, str) or not re.fullmatch(r"[A-Z]+-[0-9]{1,6}", task_id):
        raise ValueError("invalid task id")
    if not isinstance(parent_sha, str) or not _SHA.fullmatch(parent_sha):
        raise ValueError("invalid parent SHA")
    if path.is_symlink() or not path.is_file():
        raise ValueError("receipt must be a regular non-symlink file")
    with path.open("rb") as stream:
        raw = stream.read(_MAX_RECEIPT_BYTES + 1)
    if len(raw) > _MAX_RECEIPT_BYTES:
        raise ValueError("receipt exceeds size budget")
    receipt = json.loads(raw)
    return verify_github_receipt(
        receipt, expected_task_id=task_id, expected_parent_sha=parent_sha,
        repository="s58hjw2twn-netizen/Sonny2", fetch_json=fetch_json,
    )


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--receipt", required=True, type=Path)
    parser.add_argument("--task-id", required=True)
    parser.add_argument("--parent-sha", required=True)
    args = parser.parse_args(argv)
    try:
        result = check_receipt_file(args.receipt, task_id=args.task_id,
                                    parent_sha=args.parent_sha)
    except (ValueError, OSError, TypeError, KeyError, json.JSONDecodeError) as exc:
        print(json.dumps({"verified": False, "error": str(exc)}))
        return 1
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
